class LedgerUnavailable(Exception):
    """The ledger file could not be opened read-only."""


def _now_ist() -> datetime:
    return datetime.now(tz=IST)


def _data_kind(source: str | None, filename: str | None = None) -> str:
    """Labels a dataset so the UI can never present one kind of data as another.

    The three kinds that exist today are genuinely different things, and
    collapsing any two of them would mislead:

      SAMPLE_SYNTHETIC  generated by scripts/generate_sample_data.py. Describes
                        no real company and supports no conclusion whatsoever.
      NSE_BHAVCOPY_EOD  real exchange-published end-of-day data, from a UDiFF
                        bhavcopy file the user downloaded by hand. Real, but
                        unadjusted for corporate actions and EOD-only.
      HISTORICAL_CSV    a CSV the user supplied. Real or not — this app cannot
                        tell, so the label claims only its provenance.

    "live", "delayed" and "real-time" are deliberately not possible return
    values: no provider in this version supplies any of them.
    """

    raw = source or ""
    if raw.startswith("nse-udiff-bhavcopy"):
        return "NSE_BHAVCOPY_EOD"

    name = (filename or raw).upper()
    if "SAMPLE" in name:
        return "SAMPLE_SYNTHETIC"
    return "HISTORICAL_CSV"


